const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../poster-liquid-chrome.js'), 'utf8');
const classSource = source.slice(source.indexOf('class InteractiveFluidStage'), source.indexOf('// 全局注册与挂载 API'));
const document = { hidden: false, body: { dataset: { ambient: 'on', ambientEditing: 'false' } } };
let scheduled = 0, now = 16;
const Stage = vm.runInNewContext(`${classSource}; InteractiveFluidStage`, {
  document, performance: { now: () => now }, requestAnimationFrame: () => scheduled++
});
const stage = Object.create(Stage.prototype);
stage.gl = {};
stage.state = { running: true, lastTime: 0, elapsed: 0, mouse: { x: .5, y: .5 },
  targetMouse: { x: .5, y: .5 }, velocity: { x: 0, y: 0 }, disturbance: 0, click: { age: -1 } };
const renders = [];
stage.render = time => renders.push(time);
stage.loop();
assert.equal(renders.length, 1);
assert.equal(scheduled, 1);
const elapsed = stage.state.elapsed;
document.body.dataset.ambientEditing = 'true'; now += 16; stage.loop();
assert.equal(renders.length, 1, 'Editing freezes liquid rendering');
assert.equal(stage.state.elapsed, elapsed, 'Editing freezes liquid time');
document.body.dataset.ambient = 'off'; stage.loop();
assert.equal(stage.state.running, false);
assert.equal(renders.length, 1, 'Off does not redraw after initial frame');
document.body.dataset.ambient = 'on'; document.body.dataset.ambientEditing = 'false'; now += 16; stage.start();
assert.equal(renders.length, 2, 'Motion restarts without pointer input');
document.hidden = true; stage.loop();
assert.equal(stage.state.running, false);
assert.equal(renders.length, 2, 'Hidden tab does not render');
const staticStage = Object.create(Stage.prototype);
staticStage.state = { running: true }; staticStage.render = time => renders.push(time);
document.hidden = false; document.body.dataset.ambient = 'off'; staticStage.loop();
assert.equal(renders.at(-1), 0, 'Off at startup retains a static background');
console.log('PASS: liquid motion pauses for editing/off/hidden, resumes, and retains a static fallback');
const sidebar = fs.readFileSync(path.join(__dirname, '../sidebar-motion.js'), 'utf8');
const floatLoop = sidebar.slice(sidebar.indexOf('function updateCanvasFloatLoop()'), sidebar.indexOf('// --- 3.'));
const properties = new Map();
const style = { transform: '', setProperty: (key, value) => properties.set(key, value), removeProperty: key => properties.delete(key) };
const tiltTarget = { x: 2, y: 2 }, tiltCurrent = { x: 2, y: 2 };
const context = vm.createContext({ document, tiltTarget, tiltCurrent, canvasWraps: [{ style }], requestAnimationFrame() {} });
document.body.dataset.ambient = 'on'; document.body.dataset.ambientEditing = 'false';
vm.runInContext(floatLoop + '; updateCanvasFloatLoop();', context);
assert.match(style.transform, /perspective/);
assert.equal(properties.size, 2, 'Parallax adjusts shadow position, retaining CSS thickness');
document.body.dataset.ambientEditing = 'true'; vm.runInContext('updateCanvasFloatLoop()', context);
assert.equal(style.transform, '', 'Editing resets perspective for accurate canvas selection');
assert.equal(properties.size, 0);
document.body.dataset.ambientEditing = 'false'; document.body.dataset.ambient = 'off';
tiltTarget.x = tiltCurrent.x = 2; vm.runInContext('updateCanvasFloatLoop()', context);
assert.equal(style.transform, '', 'Motion off disables card parallax');
console.log('PASS: card perspective respects editing and motion off while preserving thickness');
let pointerMove;
const pointerStage = { addEventListener(type, handler) { if (type === 'pointermove') pointerMove = handler; },
  getBoundingClientRect: () => ({ left: 0, top: 0, width: 1000, height: 1000 }) };
context.stages = [pointerStage];
vm.runInContext(sidebar.slice(sidebar.indexOf('stages.forEach((stage)'), sidebar.indexOf('function updateCanvasFloatLoop()')), context);
document.body.dataset.ambient = 'on';
pointerMove({ clientX: 950, clientY: 50, target: { closest: () => null } });
assert.ok(Math.abs(tiltTarget.x - 8.55) < 1e-9);
assert.ok(Math.abs(tiltTarget.y - 8.55) < 1e-9);
pointerMove({ clientX: 950, clientY: 50, target: { closest: () => ({}) } });
assert.equal(tiltTarget.x, 0, 'Canvas entry keeps editing geometry stable');
console.log('PASS: stage edge targets a stronger tilt, canvas editing remains neutral');
